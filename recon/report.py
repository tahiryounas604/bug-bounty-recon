"""Markdown + JSON report generation for a recon run."""

from __future__ import annotations

import json
import os


def build_report_data(
    domain: str,
    crtsh_subdomains: list[str],
    dns_found: dict[str, list[str]],
    live_results: list[dict],
    port_results: dict[str, dict[int, bool]],
    nuclei_result: dict,
    wildcard_dns: bool = False,
) -> dict:
    """Assemble the single results dict that both outputs are built from."""
    all_subdomains = sorted(set(crtsh_subdomains) | set(dns_found))
    live_hosts = [r for r in live_results if r["alive"]]
    return {
        "domain": domain,
        "summary": {
            "crtsh_subdomains": len(crtsh_subdomains),
            "dns_probe_found": len(dns_found),
            "total_subdomains": len(all_subdomains),
            "live_hosts": len(live_hosts),
            "nuclei_ran": bool(nuclei_result.get("ran")),
            "wildcard_dns": wildcard_dns,
        },
        "subdomains": all_subdomains,
        "crtsh_subdomains": crtsh_subdomains,
        "dns_probe": dns_found,
        "live_hosts": live_results,
        "ports": port_results,
        "nuclei": nuclei_result,
    }


def render_markdown(data: dict) -> str:
    """Render the results dict as a Markdown report."""
    domain = data["domain"]
    summary = data["summary"]
    lines = [
        f"# Recon report — {domain}",
        "",
        "Generated by **bug-bounty-recon** v0.1.0.",
        "",
        "## Summary",
        "",
        "| Metric | Count |",
        "| --- | ---: |",
        f"| Subdomains from crt.sh | {summary['crtsh_subdomains']} |",
        f"| Subdomains from DNS probe | {summary['dns_probe_found']} |",
        f"| Total unique subdomains | {summary['total_subdomains']} |",
        f"| Live hosts | {summary['live_hosts']} |",
        f"| Nuclei scan ran | {'yes' if summary['nuclei_ran'] else 'no'} |",
        f"| Wildcard DNS detected | {'yes — DNS-probe hits unreliable' if summary.get('wildcard_dns') else 'no'} |",
        "",
        "## Subdomains",
        "",
    ]
    if summary.get("wildcard_dns"):
        lines.append(
            "> **Warning: wildcard DNS detected.** Random labels resolve, so "
            "DNS-probe hits below cannot be trusted as real subdomains. "
            "Rely on the crt.sh results and the live-host probe instead."
        )
        lines.append("")
    if data["subdomains"]:
        lines.extend(f"- `{host}`" for host in data["subdomains"])
    else:
        lines.append("_None found._")
    lines += ["", "## Live hosts", ""]
    live = [r for r in data["live_hosts"] if r["alive"]]
    if live:
        lines += [
            "| Host | Scheme | Status | Server | Title |",
            "| --- | --- | ---: | --- | --- |",
        ]
        for item in live:
            title = (item.get("title") or "").replace("|", "\\|")
            lines.append(
                f"| `{item['host']}` | {item.get('scheme', '')} | "
                f"{item.get('status', '')} | {item.get('server', '')} | {title} |"
            )
        dead = [r for r in data["live_hosts"] if not r["alive"]]
        if dead:
            lines += ["", f"_Not reachable: {', '.join(r['host'] for r in dead)}_"]
    else:
        lines.append("_No live hosts._")
    lines += ["", "## Open ports", ""]
    if data["ports"]:
        lines += ["| Host | Open ports |", "| --- | --- |"]
        for host, ports in sorted(data["ports"].items()):
            open_ports = [str(p) for p, is_open in sorted(ports.items()) if is_open]
            lines.append(f"| `{host}` | {', '.join(open_ports) or 'none'} |")
    else:
        lines.append("_No port checks performed._")
    lines += ["", "## Nuclei", ""]
    nuclei = data["nuclei"]
    if nuclei.get("ran"):
        lines.append(
            f"Scan ran (exit code {nuclei.get('returncode')}). "
            f"Findings: `{nuclei.get('findings_file')}`"
        )
    else:
        lines.append(nuclei.get("note", "Nuclei scan did not run."))
    lines += [
        "",
        "---",
        "",
        "_Scan only targets you are authorized to test._",
        "",
    ]
    return "\n".join(lines)


def write_reports(data: dict, output_dir: str) -> dict[str, str]:
    """Write ``report.md`` and ``report.json`` into ``output_dir``.

    Returns {"markdown": path, "json": path}.
    """
    os.makedirs(output_dir, exist_ok=True)
    md_path = os.path.join(output_dir, "report.md")
    json_path = os.path.join(output_dir, "report.json")
    with open(md_path, "w", encoding="utf-8") as handle:
        handle.write(render_markdown(data))
    with open(json_path, "w", encoding="utf-8") as handle:
        json.dump(data, handle, indent=2, sort_keys=True)
        handle.write("\n")
    return {"markdown": md_path, "json": json_path}
